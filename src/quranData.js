export const TOTAL_PAGES = 604;

// صفحة بداية كل جزء
export const JUZ_START = [
  1, 22, 42, 62, 82, 102, 121, 142, 162, 182, 201, 222, 242, 262, 282,
  302, 322, 342, 362, 382, 402, 422, 442, 462, 482, 502, 522, 542, 562, 582,
];

export const SURAHS = RAW.map(([number, name, ayahs, start, type], i) => {
  // آخر صفحة في السورة = صفحة بداية السورة التالية (أو 604)
  // إذا بدأت السورة التالية في نفس الصفحة فالسورة تنتهي في تلك الصفحة أيضاً
  const nextStart = i < RAW.length - 1 ? RAW[i + 1][3] : TOTAL_PAGES + 1;
  const end = Math.max(start, nextStart - 1);
  // ملاحظة: الصفحة التي تبدأ فيها سورة جديدة تُحسب للسورة الجديدة
  const pages = [];
  for (let p = start; p <= end; p++) pages.push(p);
  return { number, name, ayahs, start, end, pages, type };
});

export function juzOfPage(page) {
  let j = 1;
  for (let i = 0; i < JUZ_START.length; i++) if (page >= JUZ_START[i]) j = i + 1;
  return j;
}

export function surahsOfPage(page) {
  return SURAHS.filter((s) => page >= s.start && page <= s.end);
}

